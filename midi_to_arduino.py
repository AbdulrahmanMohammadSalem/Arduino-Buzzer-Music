import argparse
from collections import Counter
from pathlib import Path

import mido

def generate_tones_string(frequencies, durations, articulation):
    result = ''

    for i in range(len(frequencies)):
        duration = durations[i]

        if frequencies[i] > 0:
            soundTime = int(duration * articulation)

            if soundTime < 1:
                soundTime = 1

            result += f'\tf({frequencies[i]}, {soundTime}, {duration - soundTime});\n'
        else:
            result += f'\tg({duration});\n'

    return result

def midi_to_arduino(
    midi_path,
    output_path,
    buzzer_pin=8,
    transpose=0,
    articulation=0.90,
):
    midi = mido.MidiFile(midi_path)

    # Each event is (absolute time in seconds, event type, note).
    events = []
    current_time = 0.0
    active_notes = Counter()
    segments = []

    # Mido merges tracks and converts delta times to seconds,
    # accounting for tempo changes.
    for msg in midi:
        current_time += msg.time

        if msg.type == "note_on" and msg.velocity > 0:
            events.append((current_time, 1, msg.note + transpose))

        elif msg.type == "note_off" or (
            msg.type == "note_on" and msg.velocity == 0
        ):
            events.append((current_time, -1, msg.note + transpose))

    if not events:
        raise ValueError("The MIDI file contains no playable notes.")

    # Group events occurring at the same time.
    events.sort(key=lambda event: event[0])

    previous_time = events[0][0]
    index = 0

    while index < len(events):
        event_time = events[index][0]

        # Play the highest currently active note.
        duration = event_time - previous_time

        if duration > 0:
            note = max(active_notes, default=0)
            segments.append((note, round(duration * 1000)))

        # Process every event at this exact timestamp.
        while index < len(events) and events[index][0] == event_time:
            _, event_type, note = events[index]

            if event_type == 1:
                active_notes[note] += 1
            elif active_notes[note] > 0:
                active_notes[note] -= 1
                if active_notes[note] == 0:
                    del active_notes[note]

            index += 1

        previous_time = event_time

    # MIDI note numbers -> frequencies in Hz.
    # note 0 is reserved for rests.
    def frequency(note):
        if note == 0:
            return 0

        value = round(440 * 2 ** ((note - 69) / 12))

        # Arduino tone() works with positive frequencies.
        return max(1, value)

    frequencies = [frequency(note) for note, _ in segments]
    durations = [duration for _, duration in segments]

    # Split long delays because Arduino delay() accepts
    # an unsigned short, and ensure all segments are positive.
    durations = [max(1, d) for d in durations]

    code = f"""// Generated from {Path(midi_path).name}
// Automatically generated by midi_to_arduino.py

const char BUZZER_PIN = {buzzer_pin};

void f(short freq, unsigned short soundTime, unsigned short del) {{
  tone(BUZZER_PIN, freq);
  delay(soundTime);
  noTone(BUZZER_PIN);
  delay(del);
}}

void g(unsigned short del) {{
  noTone(BUZZER_PIN);
  delay(del);
}}

void setup() {{
{generate_tones_string(frequencies, durations, articulation)}
}}

void loop() {{
    
}}
"""

    Path(output_path).write_text(code, encoding="utf-8")

    print(f"Conversion complete: {output_path}")
    print(f"Segments: {len(segments)}")
    print(f"Duration: {sum(durations) / 1000:.2f} seconds")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Convert a MIDI file into Arduino buzzer code."
    )

    parser.add_argument("midi", help="Input .mid or .midi file")
    parser.add_argument(
        "-o", "--output",
        default="midi_song.ino",
        help="Output Arduino sketch (default: midi_song.ino)",
    )
    parser.add_argument(
        "--pin", type=int, default=8,
        help="Buzzer pin (default: 8)",
    )
    parser.add_argument(
        "--transpose", type=int, default=0,
        help="Transpose by semitones, e.g. -12 or +12",
    )
    parser.add_argument(
        "--articulation", type=float, default=0.90,
        help="Fraction of each note spent sounding (0 to 1)",
    )

    args = parser.parse_args()

    if not 0 < args.articulation <= 1:
        parser.error("--articulation must be greater than 0 and at most 1")

    midi_to_arduino(
        args.midi,
        args.output,
        args.pin,
        args.transpose,
        args.articulation,
    )
